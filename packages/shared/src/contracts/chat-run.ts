/**
 * Cross-process contract for the desktop leader-chat run coordinator.
 *
 * A clientRunId identifies one in-memory server lease. It is intentionally
 * distinct from Mastra's agent run id and from the stable deliveryId carried
 * by the user UI message.
 */

export const CHAT_RUN_PHASES = [
  'idle',
  'starting',
  'text',
  'protected',
  'aborting',
  'terminal',
] as const

export type ChatRunPhase = (typeof CHAT_RUN_PHASES)[number]

export const CHAT_RUN_TERMINALS = ['completed', 'aborted', 'failed'] as const

export type ChatRunTerminal = (typeof CHAT_RUN_TERMINALS)[number]

export const FOLLOW_UP_SOURCES = ['direct', 'queue', 'steer', 'budget_continue'] as const

export type FollowUpSource = (typeof FOLLOW_UP_SOURCES)[number]

export type FollowUpRequestMeta = {
  deliveryId: string
  clientRunId: string
  source: FollowUpSource
}

export type ChatRunStatus = {
  threadId: string
  active: boolean
  clientRunId?: string
  deliveryId?: string
  phase: ChatRunPhase
  terminal?: ChatRunTerminal
  canStart: boolean
  canSteer: boolean
  openWorkerJobCount: number
}

export const CHAT_RUN_ABORT_INTENTS = ['stop', 'steer'] as const

export type ChatRunAbortIntent = (typeof CHAT_RUN_ABORT_INTENTS)[number]

export type ChatRunAbortReason = 'not_found' | 'stale_run' | 'not_steerable' | 'already_terminal'

export type ChatRunAbortDecision = {
  accepted: boolean
  outcome: 'terminal' | 'waiting' | 'rejected'
  reason?: ChatRunAbortReason
  status: ChatRunStatus
}

/** UUIDs are generated by the renderer for both delivery and lease identity. */
const CHAT_RUN_ID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/iu

export function isChatRunIdentifier(value: unknown): value is string {
  return typeof value === 'string' && CHAT_RUN_ID_RE.test(value)
}

export function isFollowUpSource(value: unknown): value is FollowUpSource {
  return typeof value === 'string' && (FOLLOW_UP_SOURCES as readonly string[]).includes(value)
}

export function isFollowUpRequestMeta(value: unknown): value is FollowUpRequestMeta {
  if (!value || typeof value !== 'object') return false
  const record = value as Record<string, unknown>
  return (
    isChatRunIdentifier(record.deliveryId) &&
    isChatRunIdentifier(record.clientRunId) &&
    isFollowUpSource(record.source)
  )
}

export function isChatRunAbortIntent(value: unknown): value is ChatRunAbortIntent {
  return typeof value === 'string' && (CHAT_RUN_ABORT_INTENTS as readonly string[]).includes(value)
}
